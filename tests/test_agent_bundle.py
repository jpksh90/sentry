"""The agent bundler builds one deterministic, valid Frida script (contracts/agent-bundle.md)."""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from tests.helpers import SENTRY_DIR, have_node

BUILDER = SENTRY_DIR / "core" / "agent" / "build_agent.py"


def build(out: Path, *extra: str) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, str(BUILDER), "--out", str(out), *extra], capture_output=True, text=True)


class AgentBundle(unittest.TestCase):
    def test_deterministic_and_well_formed(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            first, second = Path(tmp) / "a.js", Path(tmp) / "b.js"
            for path in (first, second):
                result = build(path)
                self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(first.read_bytes(), second.read_bytes())
            text = first.read_text(encoding="utf-8")
            self.assertTrue(text.startswith("// GENERATED by core/agent/build_agent.py"))
            self.assertIn("const EVENT_TYPE = Object.freeze(", text)
            self.assertIn("const BROWSER_SOURCES = Object.freeze(", text)
            if have_node():
                check = subprocess.run(["node", "--check", str(first)], capture_output=True, text=True)
                self.assertEqual(check.returncode, 0, check.stderr)

    def test_duplicate_top_level_name_fails(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / "core" / "events").mkdir(parents=True)
            (root / "core" / "events" / "event_types.json").write_text('{"A": "a"}', encoding="utf-8")
            (root / "one.js").write_text("function dup(){}\n", encoding="utf-8")
            (root / "two.js").write_text("function dup(){}\n", encoding="utf-8")
            manifest = root / "manifest.json"
            manifest.write_text(
                json.dumps(
                    {
                        "entries": [
                            {"kind": "vocabulary", "file": "core/events/event_types.json"},
                            {"kind": "source", "file": "one.js"},
                            {"kind": "source", "file": "two.js"},
                        ]
                    }
                ),
                encoding="utf-8",
            )
            result = build(root / "out.js", "--root", str(root), "--manifest", str(manifest))
            self.assertEqual(result.returncode, 1)
            self.assertIn("build_agent: duplicate top-level name 'dup'", result.stderr)


if __name__ == "__main__":
    unittest.main()
