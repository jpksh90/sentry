#!/usr/bin/env python3
"""core/agent: bundle browser, native and core agent sources into one Frida script (contracts/agent-bundle.md)."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HEADER = "// GENERATED by core/agent/build_agent.py — do not edit"
TOP_LEVEL_RE = re.compile(r"^(?:async\s+)?(?:function\*?|const|let|var|class)\s+([A-Za-z_$][\w$]*)", re.M)
DEFAULT_ROOT = Path(__file__).resolve().parents[2]


class BuildError(Exception):
    pass


def read(root: Path, relative: str) -> str:
    path = root / relative
    if not path.is_file():
        raise BuildError(f"missing file {relative}")
    return path.read_text(encoding="utf-8")


def render_vocabulary(root: Path, entry: dict) -> str:
    types = json.loads(read(root, entry.get("file", "core/events/event_types.json")))
    lines = ["const EVENT_TYPE = Object.freeze({"]
    lines += [f"  {name}: {json.dumps(value)}," for name, value in types.items()]
    lines.append("});")
    return "\n".join(lines)


def render_browser_source(root: Path, entry: dict) -> str:
    files = entry.get("files") or [entry["file"]]
    parts = []
    for relative in files:
        text = read(root, relative)
        if "${" in text:
            raise BuildError(f"template literal in browser source {relative}")
        parts.append(text.rstrip("\n"))
    source = "\n".join(parts)
    if entry.get("wrap") == "iife":
        source = "(function() {\n" + source + "\n})();"
    return source


def build(root: Path, manifest_path: Path) -> str:
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    entries = manifest["entries"]

    vocabulary = [render_vocabulary(root, e) for e in entries if e["kind"] == "vocabulary"]
    browser = [(e["name"], render_browser_source(root, e)) for e in entries if e["kind"] == "browser"]
    sources = [e["file"] for e in entries if e["kind"] == "source"]

    if browser:
        body = "\n".join(f"  {name}: {json.dumps(text)}," for name, text in browser)
        browser_block = "const BROWSER_SOURCES = Object.freeze({\n" + body + "\n});"
    else:
        browser_block = "const BROWSER_SOURCES = Object.freeze({});"

    declared = {"EVENT_TYPE": "<generated>", "BROWSER_SOURCES": "<generated>"}
    chunks = [HEADER, *vocabulary, browser_block]
    for relative in sources:
        text = read(root, relative)
        for name in TOP_LEVEL_RE.findall(text):
            if name in declared:
                raise BuildError(f"duplicate top-level name '{name}' ({declared[name]} and {relative})")
            declared[name] = relative
        chunks.append(f"// --- {relative}\n" + text.rstrip("\n"))

    return "\n\n".join(chunks) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT, help="Directory containing browser/, native/ and core/.")
    parser.add_argument("--manifest", type=Path, default=None, help="Manifest path (default: <root>/core/agent/manifest.json).")
    parser.add_argument("--out", type=Path, required=True, help="Output path for the bundled agent.")
    args = parser.parse_args()

    root = args.root.resolve()
    manifest = args.manifest or root / "core" / "agent" / "manifest.json"
    try:
        output = build(root, manifest)
    except BuildError as error:
        print(f"build_agent: {error}", file=sys.stderr)
        return 1

    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
